#!/usr/bin/env python3
"""Interactive .env generator for the Telegram support bot.

Run once per deployment:

    python scripts/setup.py

Prompts for the few required secrets, auto-generates the dashboard session
secret, and writes a ready-to-use .env file. Stdlib only — safe to run before
installing dependencies.
"""

from __future__ import annotations

import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ENV_PATH = ROOT / ".env"


def _c(text: str, code: str) -> str:
    # Minimal ANSI colour; harmless if the terminal ignores it.
    return f"\033[{code}m{text}\033[0m"


def _clean(s: str) -> str:
    # Strip surrounding whitespace and a stray byte-order mark. A piped UTF-8 BOM
    # shows up either as U+FEFF (UTF-8 stdin) or, on a legacy Windows console,
    # mojibake'd through the code page (cp1251 → "п»ї", cp866 → "я╗┐"). No real
    # token/id/password/email starts with these, so dropping a leading one is safe.
    s = s.strip()
    for bom in (chr(0xFEFF), "п»ї", "я╗┐"):
        if s.startswith(bom):
            s = s[len(bom):]
            break
    return s.strip()


def ask(prompt: str, *, required: bool = False, default: str = "", secret: bool = False) -> str:
    hint = f" [{default}]" if default else ""
    while True:
        raw = _clean(input(f"{prompt}{hint}: "))
        if not raw and default:
            return default
        if raw or not required:
            return raw
        print(_c("  This one is required.", "33"))


def ask_int(prompt: str, *, required: bool = False) -> str:
    while True:
        raw = _clean(input(f"{prompt}: "))
        if not raw and not required:
            return raw
        try:
            int(raw)
            return raw
        except ValueError:
            print(_c("  Needs to be a whole number, e.g. -1001234567890.", "33"))


def main() -> int:
    # Emit UTF-8 regardless of the console code page so the wizard never crashes
    # on a glyph the legacy Windows console can't encode (e.g. ✓).
    for _stream in (sys.stdout, sys.stderr):
        try:
            _stream.reconfigure(encoding="utf-8", errors="replace")
        except Exception:
            pass

    print(_c("\n=== Spooldesk setup ===\n", "1;36"))

    if ENV_PATH.exists():
        ans = input(_c(".env already exists. Overwrite it? [y/N]: ", "33")).strip().lower()
        if ans not in ("y", "yes"):
            print("Cancelled. The existing .env was left alone.")
            return 0

    print("Where these come from:")
    print("  • BOT_TOKEN        — @BotFather in Telegram, the /newbot command.")
    print("  • ADMIN_CHAT_ID    — id of the group tickets are posted to. Forward")
    print("                       any message from it to @getmyid_bot to find out.")
    print("  • ACCESS_PASSWORD  — password for the first sign-in, as admin@local.\n")

    bot_token = ask("BOT_TOKEN", required=True)
    admin_chat_id = ask_int("ADMIN_CHAT_ID", required=True)

    access_password = ask("ACCESS_PASSWORD (blank = generate one)", required=False)
    generated_pw = False
    if not access_password:
        access_password = secrets.token_urlsafe(12)
        generated_pw = True

    gemini = ask("GEMINI_API_KEY (optional, Enter to skip)", required=False)

    dash_secret = secrets.token_urlsafe(48)

    content = f"""# Generated by scripts/setup.py — NEVER commit this file.

# --- Bot ---
BOT_TOKEN={bot_token}
ADMIN_CHAT_ID={admin_chat_id}
DATABASE_URL=sqlite+aiosqlite:///./support.db
ACCESS_PASSWORD={access_password}

# --- AI (optional — if absent, AI features stay off) ---
GEMINI_API_KEY={gemini}
GEMINI_MODEL=gemini-2.5-flash

# --- Dashboard ---
# Stable secret for signing dashboard session cookies (auto-generated).
DASH_SECRET_KEY={dash_secret}
# Set to true ONLY when serving over HTTPS (Cloudflare, reverse proxy, etc).
DASH_COOKIE_SECURE=false

# Log level for both bot and dashboard
LOG_LEVEL=INFO
"""

    ENV_PATH.write_text(content, encoding="utf-8")

    print(_c("\n✓ .env written.", "1;32"))
    print("\nDashboard sign-in:")
    print(f"  Login:    {_c('admin@local', '1')}")
    print(f"  Password: {_c(access_password, '1')}" + (_c("  (generated — save it now)", "33") if generated_pw else ""))
    print("\nNext:")
    print("  Docker:   docker compose up -d --build   →  http://localhost:8000")
    print("  By hand:  start the bot and the dashboard — see DEPLOY.md.\n")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (KeyboardInterrupt, EOFError):
        print("\nCancelled.")
        sys.exit(1)
